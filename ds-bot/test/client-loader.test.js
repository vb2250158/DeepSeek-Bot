import { test } from 'node:test'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { runInNewContext } from 'node:vm'
import { thinClientEntry } from '../scripts/build-client.mjs'

function scope() {
  const calls = []
  const disposers = []
  const fiber = { uid: 1 }
  let application = Promise.resolve()
  return { calls, fiber, record: value => calls.push(value),
    effect: (execute, label) => { calls.push(label); disposers.push(execute()) },
    track: operation => { application = operation.catch(() => {}); return operation },
    // Cordis clears uid immediately but waits for pending apply before cleanup.
    dispose: () => { fiber.uid = null; return application.then(() => { for (const off of disposers.splice(0).reverse()) off() }) } }
}

function loader(app, fetcher, require = () => { throw new Error('Unexpected platform import') }) {
  let registration
  const warnings = []
  const realm = { window: { __ModuleLoader__: { load: value => { registration = value } } },
    fetch: fetcher, console: { warn: (...args) => warnings.push(args) },
    __dsBotHeavy: { apply: () => { throw new Error('Stale global module must never run') } } }
  runInNewContext(thinClientEntry(app), realm)
  const entry = registration.factory(require)
  return { apply: ctx => ctx.track(entry.apply(ctx)), warnings }
}

test('content hash addresses exact generated bytes and apply still waits for registration completion', async () => {
  const app = 'module.exports = { apply: ctx => { ctx.record("heavy"); return ctx.pending } }'
  const digest = createHash('sha256').update(app).digest('hex')
  const response = Promise.withResolvers()
  const pending = Promise.withResolvers()
  const ctx = scope()
  ctx.pending = pending.promise
  let requested
  const loaded = loader(app, (url, options) => { requested = { url, options }; return response.promise })
  let finished = false
  const applying = loaded.apply(ctx).then(() => { finished = true })
  assert.deepEqual(ctx.calls, [])
  assert.equal(requested.url, `/api/ds-bot-client-app?v=${digest}`)
  assert.equal(requested.options.credentials, 'same-origin')
  response.resolve(new Response(app))
  await new Promise(resolve => setImmediate(resolve))
  assert.deepEqual(ctx.calls, ['heavy'])
  assert.equal(finished, false)
  pending.resolve()
  await applying
  assert.equal(finished, true)
  assert.equal(loaded.warnings.length, 0)
  await ctx.dispose()
  assert.equal(requested.options.signal, undefined)
})

test('unload waits for a pending fetch but never evaluates or applies its late response', async () => {
  const app = 'require("probe"); module.exports = { apply: ctx => ctx.record("late") }'
  const response = Promise.withResolvers()
  let options
  let evaluated = 0
  const loaded = loader(app, (_url, value) => { options = value; return response.promise }, () => { evaluated++ })
  const ctx = scope()
  const applying = loaded.apply(ctx)
  let disposed = false
  const disposing = ctx.dispose().then(() => { disposed = true })
  await new Promise(resolve => setImmediate(resolve))
  assert.equal(ctx.fiber.uid, null)
  assert.equal(disposed, false)
  assert.equal(options.signal, undefined)
  response.resolve(new Response(app))
  await Promise.all([applying, disposing])
  assert.equal(disposed, true)
  assert.equal(evaluated, 0)
  assert.deepEqual(ctx.calls, [])
  assert.equal(loaded.warnings.length, 0)
})

test('unload while the response body is pending prevents evaluation and registrations', async () => {
  const app = 'require("probe"); module.exports = { apply: ctx => ctx.record("late body") }'
  const body = Promise.withResolvers()
  const ctx = scope()
  let evaluated = 0
  const loaded = loader(app, () => Promise.resolve({ ok: true, text: () => body.promise }), () => { evaluated++ })
  const applying = loaded.apply(ctx)
  await new Promise(resolve => setImmediate(resolve))
  let disposed = false
  const disposing = ctx.dispose().then(() => { disposed = true })
  await new Promise(resolve => setImmediate(resolve))
  assert.equal(ctx.fiber.uid, null)
  assert.equal(disposed, false)
  body.resolve(app)
  await Promise.all([applying, disposing])
  assert.equal(evaluated, 0)
  assert.deepEqual(ctx.calls, [])
  assert.equal(loaded.warnings.length, 0)
})

test('a failed asset read is retriable by the next owner without a cached rejected load', async () => {
  const app = 'module.exports = { apply: ctx => ctx.record("registered") }'
  let count = 0
  const loaded = loader(app, () => Promise.resolve(++count === 1 ? new Response('missing', { status: 404 }) : new Response(app)))
  const first = scope()
  await loaded.apply(first)
  assert.deepEqual(first.calls, [])
  assert.equal(loaded.warnings.length, 1)
  await first.dispose()
  const second = scope()
  await loaded.apply(second)
  assert.deepEqual(second.calls, ['registered'])
  assert.equal(count, 2)
  await second.dispose()
})

test('evaluation and synchronous registration failures keep the existing warning path', async () => {
  for (const app of ['not valid JavaScript !', 'module.exports = { apply: () => { throw new Error("registration failed") } }']) {
    const ctx = scope()
    const loaded = loader(app, () => Promise.resolve(new Response(app)))
    await loaded.apply(ctx)
    assert.equal(loaded.warnings.length, 1)
    assert.equal(loaded.warnings[0][0], '[ds-bot] deferred client')
    await ctx.dispose()
  }
})

test('asynchronous registration failure still rejects plugin activation', async () => {
  const app = 'module.exports = { apply: async () => { throw new Error("async registration failed") } }'
  const ctx = scope()
  const loaded = loader(app, () => Promise.resolve(new Response(app)))
  await assert.rejects(loaded.apply(ctx), /async registration failed/u)
  assert.equal(loaded.warnings.length, 0)
  await ctx.dispose()
})

test('reload evaluates current platform imports and the new artifact instead of stale global exports', async () => {
  const oldApp = 'const platform = require("platform"); module.exports = { apply: ctx => ctx.record(platform + " old") }'
  const nextApp = 'const platform = require("platform"); module.exports = { apply: ctx => ctx.record(platform + " new") }'
  const first = scope()
  await loader(oldApp, () => Promise.resolve(new Response(oldApp)), () => 'first').apply(first)
  await first.dispose()
  const second = scope()
  await loader(nextApp, () => Promise.resolve(new Response(nextApp)), () => 'second').apply(second)
  assert.deepEqual(first.calls, ['first old'])
  assert.deepEqual(second.calls, ['second new'])
  await second.dispose()
})
